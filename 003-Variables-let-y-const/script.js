// Capítulo 003 - Variables: let y const
// ==========================================


// let permite reasignar un valor.
let edad = 30;

console.log("Edad inicial:", edad);

// Cambiamos el valor de la variable.
edad = 31;

console.log("Nueva edad:", edad);


// const no permite reasignar la variable.
const nombre = "Jonatan";

console.log("Nombre:", nombre);


// Podemos utilizar las variables juntas.
console.log(nombre + " tiene " + edad + " años.");
