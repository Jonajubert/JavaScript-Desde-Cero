// STRING
// Permite almacenar texto.
const nombre = "Jonatan";


// NUMBER
// Permite almacenar números.
const edad = 30;
const altura = 1.75;


// BOOLEAN
// Solo puede representar true o false.
const estudiante = true;


// UNDEFINED
// Declaramos la variable,
// pero todavía no le asignamos un valor.
let ciudad;


// NULL
// Indicamos intencionalmente
// que no existe un valor.
const telefono = null;


// Mostramos los valores.
console.log(nombre);
console.log(edad);
console.log(altura);
console.log(estudiante);
console.log(ciudad);
console.log(telefono);


// typeof permite consultar
// el tipo de un valor.
console.log(typeof nombre);
console.log(typeof edad);
console.log(typeof estudiante);
