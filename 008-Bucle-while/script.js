// Declaramos e inicializamos el contador.
let contador = 1;


// Repetimos mientras la condición sea verdadera.
while (contador <= 5) {

    // Mostramos el valor actual.
    console.log(`Número: ${contador}`);

    // Incrementamos el contador.
    contador++;
}


console.log("Fin del programa.");
